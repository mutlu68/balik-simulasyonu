export function turBul(kimlik: string): Tur {
  const tur = TURLER.find((t) => t.kimlik === kimlik);
  if (!tur) throw new Error(`Bilinmeyen tür: ${kimlik}`);
  return tur;
}

/**
 * Oyuncu da bir çipura; evre ilerledikçe hem büyüyor hem rengi altın tona kayıyor.
 * Türün kendisini kopyalayıp sadece paleti değiştiriyoruz.
 */
export function oyuncuGorunumu(evre: number): TurGorunumu {
  const temel = turBul("cipura").gorunum;
  const olgunluk = Math.max(0, Math.min(1, evre / 4));
  // Yavruyken gümüş-mavi, olgunlaştıkça sırt koyulaşıp altın tona kayıyor.
  return {
    ...temel,
    sirt: [
      Math.round(64 + olgunluk * 34),
      Math.round(84 + olgunluk * 12),
      Math.round(104 - olgunluk * 44),
    ],
    yan: [
      Math.round(214 + olgunluk * 16),
      Math.round(222 - olgunluk * 8),
      Math.round(228 - olgunluk * 56),
    ],
    karin: [248, 248, 244],
    yuzgec: [
      Math.round(112 + olgunluk * 36),
      Math.round(140 - olgunluk * 8),
      Math.round(164 - olgunluk * 54),
    ],
    seritRengi: [236, 198, 92],
    seritSayisi: 1,
  };
}
