/**
 * Karadeniz / Akdeniz tür tablosu.
 *
 * Her tür hem nasıl göründüğünü (omurga çizimi parametreleri) hem nasıl davrandığını
 * (sürü eğilimi, ürkeklik, sevdiği derinlik, diyet) tek yerde tanımlar. Yeni bir balık
 * eklemek için başka hiçbir dosyaya dokunmak gerekmiyor.
 *
 * Derinlikler su sütununa oranlı verilir: 0 = yüzey, 1 = kum. Sahne boyu pencereyle
 * değiştiği için mutlak değer tutmak yanlış olurdu.
 *
 * **İki deniz tek resifte.** Sahne bölünmüyor; ayrım `derinlik` bandından geliyor.
 * Karadeniz türleri sığ ve serin bandı (yüzey sürüleri, kumlu dip) tutuyor, Akdeniz
 * türleri açık suyu ve kayalık dibi. `deniz` alanı bu yerleşimin niyetini kayda
 * geçiriyor — tür eklerken hangi bandın doldurulduğu görülebilsin diye.
 */
import type { TurGorunumu } from "../render/fish3d";
import type { GidaAdi } from "./food";

export interface Tur {
  readonly kimlik: string;
  readonly ad: string;
  readonly gorunum: TurGorunumu;
  /** Boy aralığı (dünya birimi) — birey bu aralıktan rastgele seçilir. */
  readonly boy: readonly [number, number];
  /** Rahat yüzme hızı (birim/sn). */
  readonly hiz: number;
  /** Sevdiği derinlik bandı (0 = yüzey, 1 = dip). */
  readonly derinlik: readonly [number, number];
  /** 0 = tek gezer, 1 = sıkı sürü. */
  readonly suruEgilimi: number;
  /** Bir grupta kaç birey doğar. */
  readonly grupBoyu: readonly [number, number];
  /** 0 = oyuncuya aldırmaz, 1 = uzaktan ürker. */
  readonly urkeklik: number;
  readonly diyet: readonly GidaAdi[];
  /** Gece aktif tür mü (gündüzcüler gece dibe çekilip yavaşlar). */
  readonly gececi: boolean;
  /** Doğma ağırlığı. */
  readonly agirlik: number;
  /** Dipte oyalanan türler (barbun, iskorpit, lahoz) kuma yapışık gezer. */
  readonly dipBalig: boolean;
  /** Hangi denizin balığı — yalnızca derinlik yerleşiminin gerekçesini taşır. */
  readonly deniz: "karadeniz" | "akdeniz" | "her-ikisi";
}

